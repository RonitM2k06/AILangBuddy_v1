"""Generate the Bengali curriculum migrations from tools/bengali_curriculum_data.py and the Kolkata First Week pack (frontend/content.js):

  0048_bengali_a1.sql   Bengali joins the CEFR catalogue at A1, with its review record, 9 lessons (the 7 First Week lessons, numbers and
                        money, help and health), their phrases, words, grammar notes and exercises, 8 situations (server roleplays) and a
                        listening pair for every lesson
  0049_bengali_a2_b1.sql  Bengali joins A2 and B1: 10 A2 and 6 B1 lessons, their grammar notes and exercises, 6 situations and a
                        listening pair for every new lesson

It reuses the Marathi generator's SQL writers (tools/gen_marathi_curriculum.py), pointed at Bengali. Run from the repository root:
python tools/gen_bengali_curriculum.py. The output is committed; a migration is never edited once released."""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import gen_marathi_curriculum as gen  # noqa: E402
import bengali_curriculum_data as data  # noqa: E402

gen.LANG = "(SELECT id FROM languages WHERE code = 'bn')"           # every SQL writer below now writes Bengali rows
gen.LANGUAGE_NAME, gen.SCRIPT_NAME = "Bengali", "Bengali script"


def first_week():
    """The 7 First Week lessons: the pack's phrases, with this file's words and exercises."""
    expr = ("var G = this; G.window = G; eval($.NSString.stringWithContentsOfFileEncodingError('" + str(ROOT / "frontend/content.js") + "', 4, null).js);"
            " JSON.stringify(PACKS.kolkata)")
    pack = json.loads(subprocess.run(["osascript", "-l", "JavaScript", "-e", expr], capture_output=True, text=True, check=True).stdout)
    out = []
    for d in pack:
        extra = data.FIRST_WEEK[d["key"]]
        phrases = [(p["hi"], p["roman"], p["en"], p["natural"]) for p in d["phrases"]]
        out.append({"slug": d["key"], "topic": d["key"], "title": gen.TITLES_A1[d["key"]], "level": "A1", "sort": d["day"], "description": extra["description"],
                    "situation": d["situation"], "tip": d["tip"], "phrases": phrases, "words": extra["words"], "exercises": extra["exercises"],
                    **({"ages": extra["ages"]} if "ages" in extra else {})})
    return out


def a1_lessons():
    return first_week() + [dict(l, level="A1", sort=8 + i) for i, l in enumerate(data.A1_LESSONS)]


def bengali_sql():
    lessons = a1_lessons()
    head = ["""-- Bengali in the server curriculum (generated by tools/gen_bengali_curriculum.py from tools/bengali_curriculum_data.py and the Kolkata
-- First Week pack, frontend/content.js PACKS.kolkata; data only). Bengali joins the CEFR catalogue at A1 only, with its review record: an
-- AI-assisted editorial pass, native-speaker review pending (docs/CONTENT_REVIEW.md). 9 lessons (the 7 First Week lessons, numbers and money,
-- help and health): their phrases (Bengali verbs do not change for the speaker's gender, so none has a feminine form), 2 words each with an
-- example, 3 grammar notes and 27 exercises (what a phrase means, translate it in Roman letters or Bengali script, fill in a word).
-- 8 situations (the 7 First Week roleplays and a late-night pharmacy) and a listening pair for every lesson. No audio files: playback uses a
-- Bengali voice of the browser where the device has one, and a labelled transcript otherwise. Corrections go in a new migration.
INSERT INTO language_levels(language_id, cefr_code) SELECT l.id, 'A1' FROM languages l WHERE l.code = 'bn';
INSERT INTO content_reviews(language_id, editorial_status, native_review_status, last_editorial_reviewed_at, known_limitations)
SELECT id, 'ai_assisted_review', 'pending', '2026-10-19',
       'Written by the LingoBuddy team with an AI-assisted editorial pass; not yet checked by a native Bengali speaker. It teaches spoken '
       || 'Kolkata Bengali. Romanised Bengali has no fixed spelling: “sh” is written as Kolkata speakers say it and long vowels are not '
       || 'marked. Fares and practical tips change over time.'
FROM languages WHERE code = 'bn';"""]
    lessons_part = gen.lesson_body(head, lessons, data.GRAMMAR, {"A1": 0}, ("A1",))
    known = [{"slug": l["slug"], "topic": l["topic"], "title": l["title"], "level": l["level"], "sort": l["sort"], "phrases": l["phrases"]} for l in lessons]
    rest = gen.situation_listening_body(["\n-- situations"], data.SITUATIONS, known, known, {"A1": 0}, {"A1": 0})
    return lessons_part + rest


def a2_b1_sql():
    a2 = [dict(l, level="A2", sort=1 + i) for i, l in enumerate(data.A2_LESSONS)]
    b1 = [dict(l, level="B1", sort=1 + i) for i, l in enumerate(data.B1_LESSONS)]
    head = ["""-- Bengali A2 and B1 (generated by tools/gen_bengali_curriculum.py from tools/bengali_curriculum_data.py; data only). Bengali joins A2 and
-- B1 in the catalogue, with the topics of Kannada's and Tamil's A2 and B1 set in and around Kolkata: 10 A2 lessons (the past, plans, favours,
-- likes, comparing, a train to Shantiniketan, shop problems, work and study, problems at home, a longer conversation) and 6 B1 lessons (having
-- to, if and when, can and can't, opinions, complaints, telling what happened), 9 grammar notes, 48 exercises, 6 situations and a listening
-- pair for every new lesson. AI-assisted editorial review only; awaiting a native speaker (docs/CONTENT_REVIEW.md). Corrections go in a new
-- migration.
INSERT INTO language_levels(language_id, cefr_code) SELECT l.id, c.code FROM languages l, cefr_levels c WHERE l.code = 'bn' AND c.code IN ('A2', 'B1');"""]
    lessons_part = gen.lesson_body(head, a2 + b1, data.A2_GRAMMAR + data.B1_GRAMMAR, {"A2": 0, "B1": 0}, ("A2", "B1"))

    def short(l):
        return {"slug": l["slug"], "topic": l["topic"], "title": l["title"], "level": l["level"], "sort": l["sort"], "phrases": l["phrases"]}
    known = [short(l) for l in a1_lessons() + a2 + b1]
    rest = gen.situation_listening_body(["\n-- A2 and B1 situations"], data.A2_SITUATIONS + data.B1_SITUATIONS, known, [short(l) for l in a2 + b1],
                                        {"A2": 0, "B1": 0}, {"A2": 0, "B1": 0})
    return lessons_part + rest


if __name__ == "__main__":
    mig = ROOT / "backend/db/migrations"
    (mig / "0048_bengali_a1.sql").write_text(bengali_sql())
    (mig / "0049_bengali_a2_b1.sql").write_text(a2_b1_sql())
    print("0048 and 0049 written")
