def situations_listening_sql(new_lessons):
    fw = first_week()
    all_lessons = fw + [{"slug": l["slug"], "topic": l["topic"], "title": l["title"], "level": l["level"], "sort": l["sort"], "phrases": l["phrases"]} for l in new_lessons]
    head = ["""-- Marathi situations (server roleplays) and listening activities (generated by tools/gen_marathi_curriculum.py; data only).
-- Situations: the 7 First Week roleplays and Help and Health at A1, and 4 at A2 (a problem in your flat, a bus to Pune, exchanging a shirt,
-- planning a trip). Each studies phrases of its lesson (learn_phrase, existing vocabulary referenced, never copied), answers the partner's
-- opening line (choose_response, the first option is right), replies to the partner (conversation, its accepted answers are also the
-- suggestions) and, for some, says a phrase from English (translate). Listening: for every Marathi lesson, "what does it mean?" (its 2nd
-- phrase) and "which phrase?" (its 3rd), the two wrong options being the lesson's next phrases. No audio files are shipped: playback uses a
-- Marathi voice of the browser where the device has one, and a labelled transcript otherwise. AI-assisted editorial review only."""]
    return situation_listening_body(head, data.SITUATIONS, all_lessons, all_lessons, {"A1": 0, "A2": 0}, {"A1": 0, "A2": 0})


def situation_listening_body(out, situations, known_lessons, listen_lessons, situation_sort, listening_sort):
    """Situations (their steps refer to phrases of `known_lessons`) and a listening pair for each of `listen_lessons`, appended to `out`."""
    all_lessons = known_lessons
    romans = {p[1] for l in all_lessons for p in expand(l["phrases"])}
    sort = dict(situation_sort)
    for s in situations:
        sort[s["level"]] += 1
        name, role = s["partner"] or (None, None)
        out.append(f"\n-- {s['level']} · {s['title']}")
        out.append(f"INSERT INTO situations(language_id, cefr_code, topic_id, slug, title, description, goal, setting, partner_name, partner_role, difficulty, sort_order, status, published_at, updated_at, revision) VALUES "
                   f"({LANG}, '{s['level']}', {topic(s['topic'])}, {q(s['slug'])}, {q(s['title'])}, {q(s['description'])}, {q(s['goal'])}, "
                   f"{q(s['setting']) if s['setting'] else 'NULL'}, {q(name) if name else 'NULL'}, {q(role) if role else 'NULL'}, {s['difficulty']}, {sort[s['level']]}, 'published', datetime('now'), datetime('now'), 1);")
        for g in s.get("ages", ()):
            out.append(f"INSERT INTO situation_age_groups(situation_id, age_group_id) VALUES ({situation(s['slug'])}, (SELECT id FROM age_groups WHERE code = '{g}'));")
        n = 0
        for roman in s["learn"]:
            assert roman in romans, (s["slug"], roman)
            n += 1
            out.append(f"INSERT INTO situation_steps(situation_id, language_id, sort_order, kind, prompt, prompt_meaning, item_id, explanation) VALUES "
                       f"({situation(s['slug'])}, {LANG}, {n}, 'learn_phrase', NULL, NULL, {item_by_roman(roman)}, NULL);")
        prompt, meaning, options = s["choose"]
        n += 1
        out.append(f"INSERT INTO situation_steps(situation_id, language_id, sort_order, kind, prompt, prompt_meaning, item_id, explanation) VALUES "
                   f"({situation(s['slug'])}, {LANG}, {n}, 'choose_response', {q(prompt)}, {q(meaning) if meaning else 'NULL'}, NULL, {q('Goal: ' + s['goal'])});")
        step = f"(SELECT id FROM situation_steps WHERE situation_id = {situation(s['slug'])} AND sort_order = {n})"
        right = s["slug"].__len__() % len(options)                # the right answer is not always first on screen
        ordered = options[1:right + 1] + [options[0]] + options[right + 1:]
        for k, o in enumerate(ordered, 1):
            out.append(f"INSERT INTO situation_step_answers(step_id, answer_text, is_correct, sort_order) VALUES ({step}, {q(o)}, {int(o == options[0])}, {k});")
        if "reply" in s:
            prompt, meaning, accepted = s["reply"]
            n += 1
            out.append(f"INSERT INTO situation_steps(situation_id, language_id, sort_order, kind, prompt, prompt_meaning, item_id, explanation) VALUES "
                       f"({situation(s['slug'])}, {LANG}, {n}, 'conversation', {q(prompt)}, {q(meaning)}, NULL, 'Reply in your own words or use one of the suggestions.');")
            step = f"(SELECT id FROM situation_steps WHERE situation_id = {situation(s['slug'])} AND sort_order = {n})"
            for k, a in enumerate(accepted, 1):
                out.append(f"INSERT INTO situation_step_answers(step_id, answer_text, is_correct, sort_order) VALUES ({step}, {q(a)}, 1, {k});")
        if "translate" in s:
            prompt, roman = s["translate"]
            hi = next(p[0] for l in all_lessons for p in expand(l["phrases"]) if p[1] == roman)
            n += 1
            out.append(f"INSERT INTO situation_steps(situation_id, language_id, sort_order, kind, prompt, prompt_meaning, item_id, explanation) VALUES "
                       f"({situation(s['slug'])}, {LANG}, {n}, 'translate', {q(prompt)}, NULL, {item_by_roman(roman)}, {q(_note())});")
            step = f"(SELECT id FROM situation_steps WHERE situation_id = {situation(s['slug'])} AND sort_order = {n})"
            for k, (a, _) in enumerate(_unique([(roman, True), (hi, True)]), 1):
                out.append(f"INSERT INTO situation_step_answers(step_id, answer_text, is_correct, sort_order) VALUES ({step}, {q(a)}, 1, {k});")

    out.append(f"\n-- listening: a pair of activities for every {LANGUAGE_NAME} lesson")
    sort = dict(listening_sort)
    for l in listen_lessons:
        phrases = [p for p in l["phrases"]]                      # the lesson's own phrases (masculine forms), in order
        for mode, idx, title, prompt in (("choose_meaning", 1, f"{l['title']}: what does it mean?", "Listen, then choose what it means."),
                                         ("choose_phrase", 2, f"{l['title']}: which phrase?", "Listen, then choose the phrase you heard.")):
            sort[l["level"]] += 1
            target = phrases[idx]
            wrong = [phrases[(idx + 1) % len(phrases)], phrases[(idx + 2) % len(phrases)]]
            difficulty = (1 if mode == "choose_meaning" else 2) + (1 if l["level"] in ("A2", "B1") else 0)
            slug = f"{l['slug']}-{'meaning' if mode == 'choose_meaning' else 'phrase'}"
            out.append(f"INSERT INTO listening_activities(language_id, cefr_code, topic_id, item_id, slug, title, mode, prompt, difficulty, sort_order, status, published_at, updated_at, revision) VALUES "
                       f"({LANG}, '{l['level']}', {topic(l['topic'])}, {item(target[0])}, {q(slug)}, {q(title)}, '{mode}', {q(prompt)}, {difficulty}, {sort[l['level']]}, 'published', datetime('now'), datetime('now'), 1);")
            options = wrong[:]
            options.insert(sort[l["level"]] % 3, target)
            labels = [o[2] if mode == "choose_meaning" else o[0] for o in options]
            assert len(set(labels)) == 3, (slug, labels)
            act = f"(SELECT id FROM listening_activities WHERE language_id = {LANG} AND slug = {q(slug)})"
            for k, o in enumerate(options, 1):
                out.append(f"INSERT INTO listening_options(activity_id, language_id, item_id, sort_order) VALUES ({act}, {LANG}, {item(o[0])}, {k});")
    return "\n".join(out) + "\n"


def b1_sql(earlier_lessons):
    b1 = [dict(l, level="B1", sort=1 + i) for i, l in enumerate(data.B1_LESSONS)]
    head = ["""-- Marathi B1 (generated by tools/gen_marathi_curriculum.py from tools/marathi_curriculum_data.py; data only). Marathi joins B1 in the
-- catalogue, with 6 lessons (obligations, if and when, can and can't, opinions, complaints, telling what happened), 5 grammar notes, 18
-- exercises, 2 situations (a complaint about the water, late for a meeting) and a listening pair for every B1 lesson. AI-assisted editorial
-- review only; awaiting a native speaker (docs/CONTENT_REVIEW.md). Corrections go in a new migration.
INSERT INTO language_levels(language_id, cefr_code) SELECT l.id, 'B1' FROM languages l WHERE l.code = 'mr';"""]
    lessons_part = lesson_body(head, b1, data.B1_GRAMMAR, {"B1": 0}, ("B1",))
    fw = first_week()
    known = fw + [{"slug": l["slug"], "topic": l["topic"], "title": l["title"], "level": l["level"], "sort": l["sort"], "phrases": l["phrases"]} for l in earlier_lessons + b1]
    listen = [{"slug": l["slug"], "topic": l["topic"], "title": l["title"], "level": "B1", "sort": l["sort"], "phrases": l["phrases"]} for l in b1]
    rest = situation_listening_body(["\n-- B1 situations and listening"], data.B1_SITUATIONS, known, listen, {"B1": 0}, {"B1": 0})
    return lessons_part + rest


if __name__ == "__main__":
    mig = ROOT / "backend/db/migrations"
    sql, new_lessons = lessons_sql()
    (mig / "0032_marathi_curriculum_a1_a2.sql").write_text(sql)
    (mig / "0033_marathi_situations_listening.sql").write_text(situations_listening_sql(new_lessons))
    (mig / "0035_marathi_b1.sql").write_text(b1_sql(new_lessons))
    print("0032, 0033 and 0035 written")
