def lessons_sql():
    lessons = [dict(l, level="A1", sort=8 + i) for i, l in enumerate(data.A1_LESSONS)] + [dict(l, level="A2", sort=1 + i) for i, l in enumerate(data.A2_LESSONS)]
    head = ["""-- Marathi curriculum through A2 (generated by tools/gen_marathi_curriculum.py from tools/marathi_curriculum_data.py; data only).
-- A1: 4 lessons after the 7 First Week lessons of 0031 (numbers and money, time and days, about me, help and health).
-- A2: 10 lessons (the past, plans, favours, likes, comparing, travel, shop problems, work and study, problems at home, a longer conversation).
-- Each lesson: 5-6 phrases (and the feminine form of any gendered one), 1-2 words with an example, exercises (what a phrase means, translate
-- it in Roman letters or Devanagari, fill in a word) and grammar notes where a pattern is taught. AI-assisted editorial review only; awaiting
-- a native speaker (docs/CONTENT_REVIEW.md). Corrections go in a new migration."""]
    return lesson_body(head, lessons, data.GRAMMAR, {"A1": 3, "A2": 0}, ("A1", "A2")), lessons


def lesson_body(out, lessons, grammar_list, grammar_sort, levels):
    """Lessons, their items, grammar notes and exercises, appended to `out` (a list of SQL lines)."""
    texts = set()
    for l in lessons:
        out.append(f"\n-- {l['level']} · {l['title']}")
        out.append(f"INSERT INTO lessons(language_id, cefr_code, slug, title, description, situation, tip, sort_order, status, published_at, updated_at, revision) VALUES "
                   f"({LANG}, '{l['level']}', {q(l['slug'])}, {q(l['title'])}, {q(l['description'])}, {q(l['situation'])}, {q(l['tip'])}, {l['sort']}, 'published', datetime('now'), datetime('now'), 1);")
        out.append(f"INSERT INTO lesson_topics(lesson_id, topic_id) VALUES ({lesson(l['slug'])}, {topic(l['topic'])});")
        for g in l.get("ages", ()):
            out.append(f"INSERT INTO lesson_age_groups(lesson_id, age_group_id) VALUES ({lesson(l['slug'])}, (SELECT id FROM age_groups WHERE code = '{g}'));")
        phrases = expand(l["phrases"])
        for hi, roman, en, natural in phrases:
            assert hi not in texts, hi
            texts.add(hi)
            out.append(f"INSERT INTO vocabulary_items(language_id, cefr_code, kind, text, pronunciation) VALUES ({LANG}, '{l['level']}', 'phrase', {q(hi)}, {q(roman)});")
            out.append(f"INSERT INTO vocabulary_translations(item_id, language_id, meaning, natural) VALUES ({item(hi)}, {EN}, {q(en)}, {q(natural)});")
        for hi, roman, meaning, example in l["words"]:
            assert hi not in texts and example in {p[0] for p in phrases}, (hi, example)
            texts.add(hi)
            out.append(f"INSERT INTO vocabulary_items(language_id, cefr_code, kind, text, pronunciation) VALUES ({LANG}, '{l['level']}', 'word', {q(hi)}, {q(roman)});")
            out.append(f"INSERT INTO vocabulary_translations(item_id, language_id, meaning, natural) VALUES ({item(hi)}, {EN}, {q(meaning)}, NULL);")
            out.append(f"INSERT INTO vocabulary_examples(item_id, example_item_id, language_id) VALUES ({item(hi)}, {item(example)}, {LANG});")
        for n, t in enumerate([p[0] for p in phrases] + [w[0] for w in l["words"]], 1):
            out.append(f"INSERT INTO lesson_vocabulary(lesson_id, item_id, language_id, sort_order) VALUES ({lesson(l['slug'])}, {item(t)}, {LANG}, {n});")

    out.append("\n-- grammar notes")
    sort = dict(grammar_sort)                                   # 0031 has A1 grammar 1-3
    for slug, level, title, explanation, examples, lesson_slugs in grammar_list:
        sort[level] += 1
        out.append(f"INSERT INTO grammar_topics(language_id, cefr_code, slug, sort_order) VALUES ({LANG}, '{level}', {q(slug)}, {sort[level]});")
        out.append(f"INSERT INTO grammar_topic_texts(grammar_topic_id, language_id, title, explanation) VALUES "
                   f"((SELECT id FROM grammar_topics WHERE language_id = {LANG} AND slug = {q(slug)}), {EN}, {q(title)}, {q(explanation)});")
        for k, ex in enumerate(examples, 1):
            assert ex in texts, ex
            out.append(f"INSERT INTO grammar_examples(grammar_topic_id, item_id, language_id, sort_order) VALUES "
                       f"((SELECT id FROM grammar_topics WHERE language_id = {LANG} AND slug = {q(slug)}), {item(ex)}, {LANG}, {k});")
        for ls in lesson_slugs:
            out.append(f"INSERT INTO lesson_grammar(lesson_id, grammar_topic_id, language_id) VALUES ({lesson(ls)}, (SELECT id FROM grammar_topics WHERE language_id = {LANG} AND slug = {q(slug)}), {LANG});")

    out.append("\n-- exercises")
    for level in levels:
        group = [l for l in lessons if l["level"] == level]
        by_roman = {p[1]: p for l in group for p in expand(l["phrases"])}
        naturals = [by_roman[l["exercises"][0]][3] for l in group]
        for i, l in enumerate(group):
            mc, tr, (fill, word) = l["exercises"]
            roman_of_lesson = {p[1] for p in expand(l["phrases"])}
            assert {mc, tr, fill} <= roman_of_lesson, (l["slug"], mc, tr, fill)
            p = by_roman[mc]
            others = [naturals[(i + k) % len(naturals)] for k in (1, 2, 3)]
            assert len(set(others + [p[3]])) == 4, (l["slug"], others)
            options = others[:]
            options.insert(l["sort"] % 4, p[3])
            _exercise(out, l, "multiple_choice", f"What does “{mc}” mean?", p, None, 1, 1, [(o, o == p[3]) for o in options])
            p = by_roman[tr]
            _exercise(out, l, "translation", f"How would you say “{p[3]}” in {LANGUAGE_NAME}? ({_note()})", p, None, 2, 3, _unique([(p[1], True), (p[0], True)]))
            p = by_roman[fill]
            words = p[1].split(" ")
            hit = [k for k, w in enumerate(words) if w.strip("?!.,").lower() == word]
            assert len(hit) == 1, (fill, word)
            w = words[hit[0]]
            bare = w.rstrip("?!.,")                              # the word as the phrase writes it (a capital stays a capital)
            words[hit[0]] = "____" + w[len(bare):]
            _exercise(out, l, "fill_blank", f"Fill in the blank: “{' '.join(words)}” ({p[3]})", p, f"Full phrase: “{p[1]}”", 3, 2, [(bare, True)])
    return "\n".join(out) + "\n"


def _exercise(out, l, kind, prompt, phrase, explanation, n, difficulty, answers):
    out.append(f"INSERT INTO exercises(lesson_id, language_id, kind, prompt, item_id, grammar_topic_id, explanation, sort_order, difficulty) VALUES "
               f"({lesson(l['slug'])}, {LANG}, '{kind}', {q(prompt)}, {item(phrase[0])}, NULL, {q(explanation) if explanation else 'NULL'}, {n}, {difficulty});")
    ex = f"(SELECT id FROM exercises WHERE lesson_id = {lesson(l['slug'])} AND sort_order = {n})"
    for k, (text, correct) in enumerate(answers, 1):
        out.append(f"INSERT INTO exercise_answers(exercise_id, answer_text, is_correct, sort_order) VALUES ({ex}, {q(text)}, {int(correct)}, {k});")


