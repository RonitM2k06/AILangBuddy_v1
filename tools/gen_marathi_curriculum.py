"""Generate the Marathi curriculum migrations from tools/marathi_curriculum_data.py and the First Week pack (frontend/content.js):

  0032_marathi_curriculum_a1_a2.sql   4 more A1 lessons and 10 A2 lessons: phrases, words, grammar notes, exercises
  0033_marathi_situations_listening.sql   12 situations (server roleplays) and a listening activity pair for every Marathi lesson

Run from the repository root: python tools/gen_marathi_curriculum.py. The output is committed; a migration is never edited once released."""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import marathi_curriculum_data as data  # noqa: E402

LANG = "(SELECT id FROM languages WHERE code = 'mr')"
EN = "(SELECT id FROM languages WHERE code = 'en')"
LANGUAGE_NAME, SCRIPT_NAME = "Marathi", "Devanagari"                  # in prompts; tools/gen_kannada_curriculum.py points all three at Kannada
TRANSLATE_NOTE = None                     # the hint after a translation prompt; None: "Roman letters or <script>." (French: accents are optional)


def _note():
    return TRANSLATE_NOTE or f"Roman letters or {SCRIPT_NAME}."


def _unique(answers):
    """Answers in order without a repeated text (a French phrase without accents is its own romanised form)."""
    seen, out = set(), []
    for text, ok in answers:
        if text not in seen:
            seen.add(text)
            out.append((text, ok))
    return out
TITLES_A1 = {"greetings": "Greetings", "transport": "Transport", "food": "Food", "shopping": "Shopping", "directions": "Directions",
             "college": "College & Work", "smalltalk": "Real Conversation"}


def q(s):
    return "'" + s.replace("'", "''") + "'"


def item(text):
    return f"(SELECT id FROM vocabulary_items WHERE language_id = {LANG} AND text = {q(text)})"


def item_by_roman(roman):
    return f"(SELECT id FROM vocabulary_items WHERE language_id = {LANG} AND pronunciation = {q(roman)} AND kind = 'phrase')"


def lesson(slug):
    return f"(SELECT id FROM lessons WHERE language_id = {LANG} AND slug = {q(slug)})"


def situation(slug):
    return f"(SELECT id FROM situations WHERE language_id = {LANG} AND slug = {q(slug)})"


def topic(slug):
    return f"(SELECT id FROM topics WHERE slug = {q(slug)})"


def first_week():
    expr = ("var G = this; G.window = G; eval($.NSString.stringWithContentsOfFileEncodingError('" + str(ROOT / "frontend/content.js") + "', 4, null).js);"
            " JSON.stringify(LANGUAGE_PACKS.mumbai.mr)")
    pack = json.loads(subprocess.run(["osascript", "-l", "JavaScript", "-e", expr], capture_output=True, text=True, check=True).stdout)
    out = []
    for d in pack:
        phrases = []
        for p in d["phrases"]:
            phrases.append((p["hi"], p["roman"], p["en"], p["natural"]) + (((p["fem"]["hi"], p["fem"]["roman"]),) if p.get("fem") else ()))
        out.append({"slug": d["key"], "topic": d["key"], "title": TITLES_A1[d["key"]], "level": "A1", "sort": d["day"], "phrases": phrases})
    return out


def expand(phrases):
    """(hi, roman, en, natural[, (fem hi, fem roman)]) -> [(hi, roman, en, natural), ...] with the feminine form as its own item."""
    out = []
    for p in phrases:
        out.append(p[:4])
        if len(p) == 5:
            out.append((p[4][0], p[4][1], p[2] + " (said by a woman)", p[3]))
    return out


