"""Generate the Telugu curriculum migration from tools/telugu_curriculum_data.py and the Hyderabad First Week pack (frontend/content.js):

  0051_telugu_a1.sql   Telugu joins the CEFR catalogue at A1, with its review record, 9 lessons (the 7 First Week lessons, numbers and
                        money, help and health), their phrases, words, grammar notes and exercises, 8 situations (server roleplays) and a
                        listening pair for every lesson

It reuses the Marathi generator's SQL writers (tools/gen_marathi_curriculum.py), pointed at Telugu. Run from the repository root:
python tools/gen_telugu_curriculum.py. The output is committed; a migration is never edited once released."""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import gen_marathi_curriculum as gen  # noqa: E402
import telugu_curriculum_data as data  # noqa: E402

gen.LANG = "(SELECT id FROM languages WHERE code = 'te')"           # every SQL writer below now writes Telugu rows
gen.LANGUAGE_NAME, gen.SCRIPT_NAME = "Telugu", "Telugu script"


def first_week():
    """The 7 First Week lessons: the pack's phrases, with this file's words and exercises."""
    expr = ("var G = this; G.window = G; eval($.NSString.stringWithContentsOfFileEncodingError('" + str(ROOT / "frontend/content.js") + "', 4, null).js);"
            " JSON.stringify(PACKS.hyderabad)")
    pack = json.loads(subprocess.run(["osascript", "-l", "JavaScript", "-e", expr], capture_output=True, text=True, check=True).stdout)
    out = []
    for d in pack:
        extra = data.FIRST_WEEK[d["key"]]
        phrases = [(p["hi"], p["roman"], p["en"], p["natural"]) for p in d["phrases"]]
        out.append({"slug": d["key"], "topic": d["key"], "title": gen.TITLES_A1[d["key"]], "level": "A1", "sort": d["day"], "description": extra["description"],
                    "situation": d["situation"], "tip": d["tip"], "phrases": phrases, "words": extra["words"], "exercises": extra["exercises"],
                    **({"ages": extra["ages"]} if "ages" in extra else {})})
    return out


def a1_lessons():
    return first_week() + [dict(l, level="A1", sort=8 + i) for i, l in enumerate(data.A1_LESSONS)]


def telugu_sql():
    lessons = a1_lessons()
    head = ["""-- Telugu in the server curriculum (generated by tools/gen_telugu_curriculum.py from tools/telugu_curriculum_data.py and the Hyderabad
-- First Week pack, frontend/content.js PACKS.hyderabad; data only). Telugu joins the CEFR catalogue at A1 only, with its review record: an
-- AI-assisted editorial pass, native-speaker review pending (docs/CONTENT_REVIEW.md). 9 lessons (the 7 First Week lessons, numbers and money,
-- help and health): their phrases (Telugu verbs do not change for the speaker's gender, so none has a feminine form), 2 words each with an
-- example, 3 grammar notes and 27 exercises (what a phrase means, translate it in Roman letters or Telugu script, fill in a word).
-- 8 situations (the 7 First Week roleplays and a late-night pharmacy) and a listening pair for every lesson. No audio files: playback uses a
-- Telugu voice of the browser where the device has one, and a labelled transcript otherwise. Corrections go in a new migration.
INSERT INTO language_levels(language_id, cefr_code) SELECT l.id, 'A1' FROM languages l WHERE l.code = 'te';
INSERT INTO content_reviews(language_id, editorial_status, native_review_status, last_editorial_reviewed_at, known_limitations)
SELECT id, 'ai_assisted_review', 'pending', '2026-10-19',
       'Written by the LingoBuddy team with an AI-assisted editorial pass; not yet checked by a native Telugu speaker. It teaches spoken '
       || 'Hyderabad Telugu. Romanised Telugu has no fixed spelling: long vowels are written double and the retroflex sounds are not '
       || 'marked. Fares and practical tips change over time.'
FROM languages WHERE code = 'te';"""]
    lessons_part = gen.lesson_body(head, lessons, data.GRAMMAR, {"A1": 0}, ("A1",))
    known = [{"slug": l["slug"], "topic": l["topic"], "title": l["title"], "level": l["level"], "sort": l["sort"], "phrases": l["phrases"]} for l in lessons]
    rest = gen.situation_listening_body(["\n-- situations"], data.SITUATIONS, known, known, {"A1": 0}, {"A1": 0})
    return lessons_part + rest


if __name__ == "__main__":
    (ROOT / "backend/db/migrations/0051_telugu_a1.sql").write_text(telugu_sql())
    print("0051 written")
