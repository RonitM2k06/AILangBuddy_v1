"""Generate the Kannada curriculum migrations from tools/kannada_curriculum_data.py and the Bengaluru First Week pack (frontend/content.js):

  0037_kannada_a1.sql   Kannada joins the CEFR catalogue at A1, with its review record, 9 lessons (the 7 First Week lessons, numbers and
                        money, help and health), their phrases, words, grammar notes and exercises, 8 situations (server roleplays) and a
                        listening pair for every lesson
  0038_kannada_a2_b1.sql  Kannada joins A2 and B1: 10 A2 and 6 B1 lessons, their grammar notes and exercises, 6 situations and a
                        listening pair for every new lesson

It reuses the Marathi generator's SQL writers (tools/gen_marathi_curriculum.py), pointed at Kannada. Run from the repository root:
python tools/gen_kannada_curriculum.py. The output is committed; a migration is never edited once released."""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import gen_marathi_curriculum as gen  # noqa: E402
import kannada_curriculum_data as data  # noqa: E402

gen.LANG = "(SELECT id FROM languages WHERE code = 'kn')"           # every SQL writer below now writes Kannada rows
gen.LANGUAGE_NAME, gen.SCRIPT_NAME = "Kannada", "Kannada script"


def first_week():
    """The 7 First Week lessons: the pack's phrases (and the feminine form of the gendered one), with this file's words and exercises."""
    expr = ("var G = this; G.window = G; eval($.NSString.stringWithContentsOfFileEncodingError('" + str(ROOT / "frontend/content.js") + "', 4, null).js);"
            " JSON.stringify(PACKS.bengaluru)")
    pack = json.loads(subprocess.run(["osascript", "-l", "JavaScript", "-e", expr], capture_output=True, text=True, check=True).stdout)
    out = []
    for d in pack:
        extra = data.FIRST_WEEK[d["key"]]
        phrases = [(p["hi"], p["roman"], p["en"], p["natural"]) + (((p["fem"]["hi"], p["fem"]["roman"]),) if p.get("fem") else ()) for p in d["phrases"]]
        out.append({"slug": d["key"], "topic": d["key"], "title": gen.TITLES_A1[d["key"]], "level": "A1", "sort": d["day"], "description": extra["description"],
                    "situation": d["situation"], "tip": d["tip"], "phrases": phrases, "words": extra["words"], "exercises": extra["exercises"],
                    **({"ages": extra["ages"]} if "ages" in extra else {})})
    return out


def kannada_sql():
    lessons = first_week() + [dict(l, level="A1", sort=8 + i) for i, l in enumerate(data.A1_LESSONS)]
    head = ["""-- Kannada in the server curriculum (generated by tools/gen_kannada_curriculum.py from tools/kannada_curriculum_data.py and the Bengaluru
-- First Week pack, frontend/content.js PACKS.bengaluru; data only). Kannada joins the CEFR catalogue at A1 only, with its review record:
-- an AI-assisted editorial pass, native-speaker review pending (docs/CONTENT_REVIEW.md). 9 lessons (the 7 First Week lessons, numbers and
-- money, help and health): their phrases (and the feminine form of the one gendered phrase), 2 words each with an example, 3 grammar notes
-- and 27 exercises (what a phrase means, translate it in Roman letters or Kannada script, fill in a word). 8 situations (the 7 First Week
-- roleplays and a late-night pharmacy) and a listening pair for every lesson. No audio files: playback uses a Kannada voice of the browser
-- where the device has one, and a labelled transcript otherwise. Corrections go in a new migration.
INSERT INTO language_levels(language_id, cefr_code) SELECT l.id, 'A1' FROM languages l WHERE l.code = 'kn';
INSERT INTO content_reviews(language_id, editorial_status, native_review_status, last_editorial_reviewed_at, known_limitations)
SELECT id, 'ai_assisted_review', 'pending', '2026-10-18',
       'Written by the LingoBuddy team with an AI-assisted editorial pass; not yet checked by a native Kannada speaker. Romanised Kannada has '
       || 'no fixed spelling: long vowels are written double and the retroflex sounds are not marked. The one gendered phrase shows its '
       || 'feminine form. Fares and practical tips change over time.'
FROM languages WHERE code = 'kn';"""]
    lessons_part = gen.lesson_body(head, lessons, data.GRAMMAR, {"A1": 0}, ("A1",))
    known = [{"slug": l["slug"], "topic": l["topic"], "title": l["title"], "level": l["level"], "sort": l["sort"], "phrases": l["phrases"]} for l in lessons]
    rest = gen.situation_listening_body(["\n-- situations"], data.SITUATIONS, known, known, {"A1": 0}, {"A1": 0})
    return lessons_part + rest


def a1_lessons():
    return first_week() + [dict(l, level="A1", sort=8 + i) for i, l in enumerate(data.A1_LESSONS)]


def a2_b1_sql():
    a2 = [dict(l, level="A2", sort=1 + i) for i, l in enumerate(data.A2_LESSONS)]
    b1 = [dict(l, level="B1", sort=1 + i) for i, l in enumerate(data.B1_LESSONS)]
    head = ["""-- Kannada A2 and B1 (generated by tools/gen_kannada_curriculum.py from tools/kannada_curriculum_data.py; data only). Kannada joins A2 and
-- B1 in the catalogue, with the topics of Marathi's A2 and B1 set in and around Bengaluru: 10 A2 lessons (the past, plans, favours, likes,
-- comparing, a trip to Mysuru, shop problems, work and study, problems at home, a longer conversation) and 6 B1 lessons (having to, if and
-- when, can and can't, opinions, complaints, telling what happened), 9 grammar notes, 48 exercises, 6 situations and a listening pair for
-- every new lesson. AI-assisted editorial review only; awaiting a native speaker (docs/CONTENT_REVIEW.md). Corrections go in a new migration.
INSERT INTO language_levels(language_id, cefr_code) SELECT l.id, c.code FROM languages l, cefr_levels c WHERE l.code = 'kn' AND c.code IN ('A2', 'B1');"""]
    lessons_part = gen.lesson_body(head, a2 + b1, data.A2_GRAMMAR + data.B1_GRAMMAR, {"A2": 0, "B1": 0}, ("A2", "B1"))
    def short(l):
        return {"slug": l["slug"], "topic": l["topic"], "title": l["title"], "level": l["level"], "sort": l["sort"], "phrases": l["phrases"]}
    known = [short(l) for l in a1_lessons() + a2 + b1]
    rest = gen.situation_listening_body(["\n-- A2 and B1 situations"], data.A2_SITUATIONS + data.B1_SITUATIONS, known, [short(l) for l in a2 + b1],
                                        {"A2": 0, "B1": 0}, {"A2": 0, "B1": 0})
    return lessons_part + rest


if __name__ == "__main__":
    mig = ROOT / "backend/db/migrations"
    (mig / "0037_kannada_a1.sql").write_text(kannada_sql())
    (mig / "0038_kannada_a2_b1.sql").write_text(a2_b1_sql())
    print("0037 and 0038 written")
