"""Generate the Tamil curriculum migrations from tools/tamil_curriculum_data.py and the Chennai First Week pack (frontend/content.js):

  0040_tamil_a1.sql   Tamil joins the CEFR catalogue at A1, with its review record, 9 lessons (the 7 First Week lessons, numbers and
                        money, help and health), their phrases, words, grammar notes and exercises, 8 situations (server roleplays) and a
                        listening pair for every lesson
  0041_tamil_a2_b1.sql  Tamil joins A2 and B1: 10 A2 and 6 B1 lessons, their grammar notes and exercises, 6 situations and a
                        listening pair for every new lesson

It reuses the Marathi generator's SQL writers (tools/gen_marathi_curriculum.py), pointed at Tamil. Run from the repository root:
python tools/gen_tamil_curriculum.py. The output is committed; a migration is never edited once released."""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import gen_marathi_curriculum as gen  # noqa: E402
import tamil_curriculum_data as data  # noqa: E402

gen.LANG = "(SELECT id FROM languages WHERE code = 'ta')"           # every SQL writer below now writes Tamil rows
gen.LANGUAGE_NAME, gen.SCRIPT_NAME = "Tamil", "Tamil script"


def first_week():
    """The 7 First Week lessons: the pack's phrases (and a feminine form, where one exists), with this file's words and exercises."""
    expr = ("var G = this; G.window = G; eval($.NSString.stringWithContentsOfFileEncodingError('" + str(ROOT / "frontend/content.js") + "', 4, null).js);"
            " JSON.stringify(PACKS.chennai)")
    pack = json.loads(subprocess.run(["osascript", "-l", "JavaScript", "-e", expr], capture_output=True, text=True, check=True).stdout)
    out = []
    for d in pack:
        extra = data.FIRST_WEEK[d["key"]]
        phrases = [(p["hi"], p["roman"], p["en"], p["natural"]) + (((p["fem"]["hi"], p["fem"]["roman"]),) if p.get("fem") else ()) for p in d["phrases"]]
        out.append({"slug": d["key"], "topic": d["key"], "title": gen.TITLES_A1[d["key"]], "level": "A1", "sort": d["day"], "description": extra["description"],
                    "situation": d["situation"], "tip": d["tip"], "phrases": phrases, "words": extra["words"], "exercises": extra["exercises"],
                    **({"ages": extra["ages"]} if "ages" in extra else {})})
    return out


def tamil_sql():
    lessons = first_week() + [dict(l, level="A1", sort=8 + i) for i, l in enumerate(data.A1_LESSONS)]
    head = ["""-- Tamil in the server curriculum (generated by tools/gen_tamil_curriculum.py from tools/tamil_curriculum_data.py and the Chennai
-- First Week pack, frontend/content.js PACKS.chennai; data only). Tamil joins the CEFR catalogue at A1 only, with its review record:
-- an AI-assisted editorial pass, native-speaker review pending (docs/CONTENT_REVIEW.md). 9 lessons (the 7 First Week lessons, numbers and
-- money, help and health): their phrases (spoken Chennai Tamil; none is gendered), 2 words each with an example, 3 grammar notes
-- and 27 exercises (what a phrase means, translate it in Roman letters or Tamil script, fill in a word). 8 situations (the 7 First Week
-- roleplays and a late-night pharmacy) and a listening pair for every lesson. No audio files: playback uses a Tamil voice of the browser
-- where the device has one, and a labelled transcript otherwise. Corrections go in a new migration.
INSERT INTO language_levels(language_id, cefr_code) SELECT l.id, 'A1' FROM languages l WHERE l.code = 'ta';
INSERT INTO content_reviews(language_id, editorial_status, native_review_status, last_editorial_reviewed_at, known_limitations)
SELECT id, 'ai_assisted_review', 'pending', '2026-10-18',
       'Written by the LingoBuddy team with an AI-assisted editorial pass; not yet checked by a native Tamil speaker. Romanised Tamil has '
       || 'no fixed spelling: long vowels are written double and the retroflex sounds are not marked. The content teaches spoken Chennai '
       || 'Tamil, which differs from written Tamil. Fares and practical tips change over time.'
FROM languages WHERE code = 'ta';"""]
    lessons_part = gen.lesson_body(head, lessons, data.GRAMMAR, {"A1": 0}, ("A1",))
    known = [{"slug": l["slug"], "topic": l["topic"], "title": l["title"], "level": l["level"], "sort": l["sort"], "phrases": l["phrases"]} for l in lessons]
    rest = gen.situation_listening_body(["\n-- situations"], data.SITUATIONS, known, known, {"A1": 0}, {"A1": 0})
    return lessons_part + rest


def a1_lessons():
    return first_week() + [dict(l, level="A1", sort=8 + i) for i, l in enumerate(data.A1_LESSONS)]


def a2_b1_sql():
    a2 = [dict(l, level="A2", sort=1 + i) for i, l in enumerate(data.A2_LESSONS)]
    b1 = [dict(l, level="B1", sort=1 + i) for i, l in enumerate(data.B1_LESSONS)]
    head = ["""-- Tamil A2 and B1 (generated by tools/gen_tamil_curriculum.py from tools/tamil_curriculum_data.py; data only). Tamil joins A2 and
-- B1 in the catalogue, with the topics of Marathi's A2 and B1 set in and around Chennai: 10 A2 lessons (the past, plans, favours, likes,
-- comparing, a trip to Puducherry, shop problems, work and study, problems at home, a longer conversation) and 6 B1 lessons (having to, if and
-- when, can and can't, opinions, complaints, telling what happened), 9 grammar notes, 48 exercises, 6 situations and a listening pair for
-- every new lesson. AI-assisted editorial review only; awaiting a native speaker (docs/CONTENT_REVIEW.md). Corrections go in a new migration.
INSERT INTO language_levels(language_id, cefr_code) SELECT l.id, c.code FROM languages l, cefr_levels c WHERE l.code = 'ta' AND c.code IN ('A2', 'B1');"""]
    lessons_part = gen.lesson_body(head, a2 + b1, data.A2_GRAMMAR + data.B1_GRAMMAR, {"A2": 0, "B1": 0}, ("A2", "B1"))
    def short(l):
        return {"slug": l["slug"], "topic": l["topic"], "title": l["title"], "level": l["level"], "sort": l["sort"], "phrases": l["phrases"]}
    known = [short(l) for l in a1_lessons() + a2 + b1]
    rest = gen.situation_listening_body(["\n-- A2 and B1 situations"], data.A2_SITUATIONS + data.B1_SITUATIONS, known, [short(l) for l in a2 + b1],
                                        {"A2": 0, "B1": 0}, {"A2": 0, "B1": 0})
    return lessons_part + rest


def more_practice_sql():
    """0042: two more A1 lessons and their listening pairs, and four more situations. The lessons' exercises take their wrong options from all
    eleven A1 lessons, so the A1 writer runs over all of them and only the new lessons' statements are kept (0040 already has the rest)."""
    a1 = a1_lessons()
    extra = [dict(l, level="A1", sort=len(a1) + 1 + i) for i, l in enumerate(data.EXTRA_A1_LESSONS)]
    everything = gen.lesson_body([], a1 + extra, [], {"A1": 0}, ("A1",)).split("\n")
    markers = [gen.q(l["slug"]) for l in extra] + [gen.q(p[0]) for l in extra for p in gen.expand(l["phrases"])] + [gen.q(w[0]) for l in extra for w in l["words"]]
    titles = {f"-- A1 · {l['title']}" for l in extra}
    kept = [line for line in everything if line in titles or any(m in line for m in markers)]
    head = ["""-- More Tamil practice (generated by tools/gen_tamil_curriculum.py from tools/tamil_curriculum_data.py; data only): two more A1 lessons
-- (Time and Days, About Me) with their words and exercises, a listening pair for each, and four more situations (meet your neighbours,
-- paying at a provision store at A1, a cab to the airport at A2, looking for a flat at B1). AI-assisted editorial review only; awaiting a
-- native speaker (docs/CONTENT_REVIEW.md). Corrections go in a new migration."""] + kept
    def short(l):
        return {"slug": l["slug"], "topic": l["topic"], "title": l["title"], "level": l["level"], "sort": l["sort"], "phrases": l["phrases"]}
    a2 = [dict(l, level="A2", sort=1 + i) for i, l in enumerate(data.A2_LESSONS)]
    b1 = [dict(l, level="B1", sort=1 + i) for i, l in enumerate(data.B1_LESSONS)]
    known = [short(l) for l in a1 + extra + a2 + b1]
    return gen.situation_listening_body(head + ["\n-- situations"], data.EXTRA_SITUATIONS, known, [short(l) for l in extra],
                                        {"A1": len(data.SITUATIONS), "A2": len(data.A2_SITUATIONS), "B1": len(data.B1_SITUATIONS)},
                                        {"A1": 2 * len(a1)})


def _new_statements(lessons, new):
    """The A-level writer's statements for `new` only: it runs over all of `lessons` (so the new lessons' multiple-choice options come from the
    whole level) and keeps the lines that name a new lesson or a new item."""
    everything = gen.lesson_body([], lessons, [], {l["level"]: 0 for l in lessons}, tuple(dict.fromkeys(l["level"] for l in lessons))).split("\n")
    markers = [gen.q(l["slug"]) for l in new] + [gen.q(p[0]) for l in new for p in gen.expand(l["phrases"])] + [gen.q(w[0]) for l in new for w in l["words"]]
    titles = {f"-- {l['level']} · {l['title']}" for l in new}
    return [line for line in everything if line in titles or any(m in line for m in markers)]


def puducherry_sql():
    """0045: Tamil practice set in Puducherry: an A2 lesson (a weekend there) with its listening pair, and three situations."""
    a1 = a1_lessons() + [dict(l, level="A1", sort=len(a1_lessons()) + 1 + i) for i, l in enumerate(data.EXTRA_A1_LESSONS)]
    a2 = [dict(l, level="A2", sort=1 + i) for i, l in enumerate(data.A2_LESSONS)]
    new = [dict(l, level="A2", sort=len(a2) + 1 + i) for i, l in enumerate(data.PUDUCHERRY_A2_LESSONS)]
    b1 = [dict(l, level="B1", sort=1 + i) for i, l in enumerate(data.B1_LESSONS)]
    head = ["""-- Tamil for Puducherry (generated by tools/gen_tamil_curriculum.py from tools/tamil_curriculum_data.py; data only): an A2 lesson, A Weekend
-- in Puducherry (renting a scooter, the beach, a café), with its words, exercises and listening pair, and three situations set there:
-- breakfast by the Promenade (A1), renting a scooter and finding the Promenade (A2). Tamil content is per language, so Chennai's learners get
-- them too. AI-assisted editorial review only; awaiting a native speaker (docs/CONTENT_REVIEW.md). Corrections go in a new migration."""]
    head += _new_statements(a2 + new, new)
    def short(l):
        return {"slug": l["slug"], "topic": l["topic"], "title": l["title"], "level": l["level"], "sort": l["sort"], "phrases": l["phrases"]}
    known = [short(l) for l in a1 + a2 + new + b1]
    a1_sit = len(data.SITUATIONS) + sum(1 for x in data.EXTRA_SITUATIONS if x["level"] == "A1")
    a2_sit = len(data.A2_SITUATIONS) + sum(1 for x in data.EXTRA_SITUATIONS if x["level"] == "A2")
    return gen.situation_listening_body(head + ["\n-- situations"], data.PUDUCHERRY_SITUATIONS, known, [short(l) for l in new],
                                        {"A1": a1_sit, "A2": a2_sit}, {"A2": 2 * len(a2)})


if __name__ == "__main__":
    mig = ROOT / "backend/db/migrations"
    (mig / "0040_tamil_a1.sql").write_text(tamil_sql())
    (mig / "0041_tamil_a2_b1.sql").write_text(a2_b1_sql())
    (mig / "0042_tamil_more_practice.sql").write_text(more_practice_sql())
    (mig / "0045_tamil_puducherry.sql").write_text(puducherry_sql())
    print("0040, 0041, 0042 and 0045 written")
