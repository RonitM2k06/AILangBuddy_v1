"""Generate the Kashmiri curriculum migration from tools/kashmiri_curriculum_data.py and Jammu & Kashmir's Kashmiri First Week pack (frontend/content.js):

  0055_kashmiri_a1.sql  Kashmiri joins the CEFR catalogue at A1, with its review record, 9 lessons (the 7 First Week lessons, numbers and
                        money, help and health), their phrases, words, grammar notes and exercises, 8 situations and a listening pair
                        for every lesson. Kashmiri is written in its Perso-Arabic script (right to left); each phrase is stored as written
                        and, as its "pronunciation", romanised; both are accepted. A DRAFT: see docs/CONTENT_REVIEW.md.

It reuses the Marathi generator's SQL writers (tools/gen_marathi_curriculum.py), pointed at Kashmiri. Run from the repository root:
python tools/gen_kashmiri_curriculum.py. The output is committed; a migration is never edited once released."""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import gen_marathi_curriculum as gen  # noqa: E402
import kashmiri_curriculum_data as data  # noqa: E402

gen.LANG = "(SELECT id FROM languages WHERE code = 'ks')"           # every SQL writer below now writes Kashmiri rows
gen.LANGUAGE_NAME, gen.SCRIPT_NAME = "Kashmiri", "Kashmiri script"


def first_week():
    """The 7 First Week lessons: the pack's phrases (and the feminine form of the gendered ones), with this file's words and exercises."""
    expr = ("var G = this; G.window = G; eval($.NSString.stringWithContentsOfFileEncodingError('" + str(ROOT / "frontend/content.js") + "', 4, null).js);"
            " JSON.stringify(PACKS.jk)")
    pack = json.loads(subprocess.run(["osascript", "-l", "JavaScript", "-e", expr], capture_output=True, text=True, check=True).stdout)
    out = []
    for d in pack:
        extra = data.FIRST_WEEK[d["key"]]
        phrases = [(p["hi"], p["roman"], p["en"], p["natural"]) + (((p["fem"]["hi"], p["fem"]["roman"]),) if p.get("fem") else ()) for p in d["phrases"]]
        out.append({"slug": d["key"], "topic": d["key"], "title": gen.TITLES_A1[d["key"]], "level": "A1", "sort": d["day"], "description": extra["description"],
                    "situation": d["situation"], "tip": d["tip"], "phrases": phrases, "words": extra["words"], "exercises": extra["exercises"],
                    **({"ages": extra["ages"]} if "ages" in extra else {})})
    return out


def kashmiri_sql():
    lessons = first_week() + [dict(l, level="A1", sort=8 + i) for i, l in enumerate(data.A1_LESSONS)]
    head = ["""-- Kashmiri in the server curriculum (generated by tools/gen_kashmiri_curriculum.py from tools/kashmiri_curriculum_data.py and Jammu & Kashmir's
-- Kashmiri First Week pack, frontend/content.js PACKS.jk; data only). Kashmiri joins the CEFR catalogue at A1, with its review
-- record: a DRAFT with an AI-assisted pass, native-speaker review pending (docs/CONTENT_REVIEW.md). 9 lessons (the 7 First Week lessons, numbers
-- and money, help and health): their phrases (and the feminine form of the gendered one), 2 words each with an example, 3 grammar notes and 27
-- exercises (what a phrase means, translate it in Roman letters or Kashmiri script, fill in a word). 8 situations and a listening pair for
-- every lesson; browsers have no Kashmiri voice, so listening shows a labelled transcript. Corrections go in a new migration.
INSERT INTO language_levels(language_id, cefr_code) SELECT l.id, 'A1' FROM languages l WHERE l.code = 'ks';
INSERT INTO content_reviews(language_id, editorial_status, native_review_status, last_editorial_reviewed_at, known_limitations)
SELECT id, 'ai_assisted_review', 'pending', '2026-10-19',
       'A DRAFT written by the LingoBuddy team with an AI-assisted pass, with lower confidence than other languages, especially in the Kashmiri '
       || 'script; not yet checked by a native Kashmiri speaker, who should check every phrase. Masculine forms are taught first; the feminine '
       || 'form is shown where it differs. Browsers have no Kashmiri voice. Fares and practical tips change over time.'
FROM languages WHERE code = 'ks';"""]
    lessons_part = gen.lesson_body(head, lessons, data.GRAMMAR, {"A1": 0}, ("A1",))
    known = [{"slug": l["slug"], "topic": l["topic"], "title": l["title"], "level": l["level"], "sort": l["sort"], "phrases": l["phrases"]} for l in lessons]
    rest = gen.situation_listening_body(["\n-- situations"], data.SITUATIONS, known, known, {"A1": 0}, {"A1": 0})
    return lessons_part + rest


if __name__ == "__main__":
    (ROOT / "backend/db/migrations/0055_kashmiri_a1.sql").write_text(kashmiri_sql())
    print("0055 written")
