"""Generate the French curriculum migration from tools/french_curriculum_data.py and the Puducherry French First Week pack (frontend/content.js):

  0044_french_a1.sql    French joins the CEFR catalogue at A1, with its review record, 9 lessons (the 7 First Week lessons, numbers and
                        money, help and health), their phrases, words, grammar notes and exercises, 8 situations and a listening pair
                        for every lesson. French is written in Roman letters: each phrase is stored as written (with accents) and,
                        as its "pronunciation", without accents; both are accepted.

It reuses the Marathi generator's SQL writers (tools/gen_marathi_curriculum.py), pointed at French. Run from the repository root:
python tools/gen_french_curriculum.py. The output is committed; a migration is never edited once released."""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import gen_marathi_curriculum as gen  # noqa: E402
import french_curriculum_data as data  # noqa: E402

gen.LANG = "(SELECT id FROM languages WHERE code = 'fr')"           # every SQL writer below now writes French rows
gen.LANGUAGE_NAME, gen.SCRIPT_NAME = "French", "French"
gen.TRANSLATE_NOTE = "Accents are optional."


def first_week():
    """The 7 First Week lessons: the pack's phrases (and the feminine form of the gendered one), with this file's words and exercises."""
    expr = ("var G = this; G.window = G; eval($.NSString.stringWithContentsOfFileEncodingError('" + str(ROOT / "frontend/content.js") + "', 4, null).js);"
            " JSON.stringify(LANGUAGE_PACKS.puducherry.fr)")
    pack = json.loads(subprocess.run(["osascript", "-l", "JavaScript", "-e", expr], capture_output=True, text=True, check=True).stdout)
    out = []
    for d in pack:
        extra = data.FIRST_WEEK[d["key"]]
        phrases = [(p["hi"], p["roman"], p["en"], p["natural"]) + (((p["fem"]["hi"], p["fem"]["roman"]),) if p.get("fem") else ()) for p in d["phrases"]]
        out.append({"slug": d["key"], "topic": d["key"], "title": gen.TITLES_A1[d["key"]], "level": "A1", "sort": d["day"], "description": extra["description"],
                    "situation": d["situation"], "tip": d["tip"], "phrases": phrases, "words": extra["words"], "exercises": extra["exercises"],
                    **({"ages": extra["ages"]} if "ages" in extra else {})})
    return out


def french_sql():
    lessons = first_week() + [dict(l, level="A1", sort=8 + i) for i, l in enumerate(data.A1_LESSONS)]
    head = ["""-- French in the server curriculum (generated by tools/gen_french_curriculum.py from tools/french_curriculum_data.py and the Puducherry
-- French First Week pack, frontend/content.js LANGUAGE_PACKS.puducherry.fr; data only). French joins the CEFR catalogue at A1, with its review
-- record: an AI-assisted editorial pass, native-speaker review pending (docs/CONTENT_REVIEW.md). 9 lessons (the 7 First Week lessons, numbers
-- and money, help and health): their phrases (and the feminine form of the two gendered ones), 2 words each with an example, 3 grammar notes
-- and 27 exercises (what a phrase means, translate it with or without accents, fill in a word). 8 situations and a listening pair for every
-- lesson; playback uses a French voice of the browser where the device has one, and a labelled transcript otherwise. Corrections go in a new
-- migration.
INSERT INTO language_levels(language_id, cefr_code) SELECT l.id, 'A1' FROM languages l WHERE l.code = 'fr';
INSERT INTO content_reviews(language_id, editorial_status, native_review_status, last_editorial_reviewed_at, known_limitations)
SELECT id, 'ai_assisted_review', 'pending', '2026-10-18',
       'Written by the LingoBuddy team with an AI-assisted editorial pass; not yet checked by a native French speaker. Standard French in '
       || 'Puducherry settings; local Franco-Pondicherrian expressions are not covered yet. Answers are accepted with or without accents.'
FROM languages WHERE code = 'fr';"""]
    lessons_part = gen.lesson_body(head, lessons, data.GRAMMAR, {"A1": 0}, ("A1",))
    known = [{"slug": l["slug"], "topic": l["topic"], "title": l["title"], "level": l["level"], "sort": l["sort"], "phrases": l["phrases"]} for l in lessons]
    rest = gen.situation_listening_body(["\n-- situations"], data.SITUATIONS, known, known, {"A1": 0}, {"A1": 0})
    return lessons_part + rest


if __name__ == "__main__":
    (ROOT / "backend/db/migrations/0044_french_a1.sql").write_text(french_sql())
    print("0044 written")
